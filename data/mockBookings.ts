// Helper function to check if a court is booked
export const isCourtBooked = (
  courtId: string,
  courtNumber: string,
  day: string,
  timeSlot: string
): boolean => {
  return mockBookings.some((booking) => {
    if (booking.courtId !== courtId || booking.courtNumber !== courtNumber) {
      return false
    }

    if (booking.timeSlot !== timeSlot) {
      return false
    }

    if (booking.isRecurring && booking.recurringPattern) {
      if (booking.recurringPattern.frequency === 'weekly') {
        return booking.recurringPattern.daysOfWeek?.includes(day) || false
      }
    } else {
      return booking.date === day
    }

    return false
  })
}

