import { Court, TimeSlotAvailability } from '@/types'
import { isCourtBooked } from './mockBookings'

// Helper function to create time slot availability
const createTimeSlots = (
  times: string[],
  totalCourts: number,
  courtNumbers: string[],
  courtId: string,
  day: string
): TimeSlotAvailability[] => {
  return times.map((time) => {
    const availableCourts = courtNumbers.map((courtNum) => ({
      number: courtNum,
      isAvailable: !isCourtBooked(courtId, courtNum, day, time),
    }))
    return {
      time,
      availableCourts,
    }
  })
}

